    /// `splice_before_commit` needs the frame; `filled_script` on a
    /// body without the banner is the identity, and the ledger
    /// region (banner-led) inverts byte for byte. `filled_script` is
    /// the TOTAL normal form — every line newline-terminated — so a
    /// body that lacks the trailing newline normalizes to what the
    /// splice writes, and the strip is a fixed point of the splice
    /// either way (the recorded hash re-derives from the file).
    #[test]
    fn splice_and_filled_are_inverses() {
        assert!(splice_before_commit("USE NS x;\n", "-- y\n").is_none());
        // The splice-less refusal names the missing terminator, not
        // the BEGIN frame.
        assert!(
            DraftError::NoCommit
                .to_string()
                .contains("final `COMMIT;` line is missing"),
            "{}",
            DraftError::NoCommit
        );
        let body = "BEGIN TRANSACTION;\nA;\nCOMMIT;\n";
        let block = format!("{LEDGER_BANNER}\nDEFINE TABLE IF NOT EXISTS t;\n");
        let spliced = splice_before_commit(body, &block).expect("splices");
        assert_eq!(spliced, format!("BEGIN TRANSACTION;\nA;\n{block}COMMIT;\n"));
        assert_eq!(filled_script(&spliced), body);
        // A body with no banner region is its own filled script.
        assert_eq!(filled_script(body), body);
        // The missing trailing newline normalizes away — the exact
        // bytes the splice writes — so the hash is a fixed point.
        let bare = "BEGIN TRANSACTION;\nCOMMIT;";
        assert_eq!(filled_script(bare), format!("{bare}\n"));
        let spliced_bare = splice_before_commit(bare, &block).expect("the frame stood");
        assert_eq!(filled_script(&spliced_bare), filled_script(bare));
        // The same fixed point with a hand-forged banner: the forged
        // region descopes, the splice's block strips with it.
        let forged = format!(
            "BEGIN TRANSACTION;\nA;\n{LEDGER_BANNER}\nDEFINE TABLE IF NOT EXISTS forged;\nCOMMIT;"
        );
        let spliced_forged = splice_before_commit(&forged, &block).expect("the frame stood");
        assert_eq!(filled_script(&spliced_forged), filled_script(&forged));
        assert_eq!(
            filled_script(&forged),
            "BEGIN TRANSACTION;\nA;\nCOMMIT;\n",
            "the forged region descopes from the hash"
        );
        // The strip keys on the banner as an EXACT whole line — the
        // one spelling the splice writes: a line that
        // merely begins with the banner text (string content quoting
        // it, no forgery intended) stays in the hashed form.
        let quoted = format!(
            "BEGIN TRANSACTION;\nA;\nINSERT INTO t VALUES ('{LEDGER_BANNER} and more');\nCOMMIT;\n"
        );
        assert_eq!(filled_script(&quoted), quoted);
    }

    /// The one-frame shape guard: a clean body passes (comments and
    /// blanks after the close ride), while both defect spellings — a
    /// hand-edit's appended statement and a second BEGIN…COMMIT block
    /// — land on the first content line after the FIRST close, named
    /// with its 1-based body line. The anchor folds case and the
    /// lexer's whitespace (the engine's reading of the close), and an
    /// unterminated `/*` after the close is the offender at its
    /// opening line. A body with no close at all is NoCommit's ground,
    /// not this guard's.
    #[test]
    fn trailing_frame_content_names_the_first_offender() {
        // Clean: the tool's shape, plus trailing comment/blanks.
        assert_eq!(
            trailing_frame_content("BEGIN TRANSACTION;\nA;\nCOMMIT;\n"),
            None
        );
        assert_eq!(
            trailing_frame_content(
                "BEGIN TRANSACTION;\nA;\nCOMMIT;\n\n   \n-- a note\n# another\n// third\n"
            ),
            None
        );
        // A multi-line block comment after the close rides too.
        assert_eq!(
            trailing_frame_content("BEGIN TRANSACTION;\nCOMMIT;\n/* spanning\nseveral lines\n*/\n"),
            None
        );
        // The appended-statement spelling: the line, 1-based.
        assert_eq!(
            trailing_frame_content("BEGIN TRANSACTION;\nA;\nCOMMIT;\nDEFINE TABLE p2a;\n"),
            Some((4, "DEFINE TABLE p2a;".to_string()))
        );
        // The second-block spelling: the FIRST `COMMIT;` anchors — the
        // second block's BEGIN is the offender (the ledger would splice
        // into the LAST commit, outside the certified frame).
        assert_eq!(
            trailing_frame_content(
                "BEGIN TRANSACTION;\nA;\nCOMMIT;\nBEGIN TRANSACTION;\nB;\nCOMMIT;\n"
            ),
            Some((4, "BEGIN TRANSACTION;".to_string()))
        );
        // A second block separated by comments still lands.
        assert_eq!(
            trailing_frame_content("BEGIN;\nCOMMIT;\n-- bridging prose\nB;\n"),
            Some((4, "B;".to_string()))
        );
        // Content AFTER an inline-closed block comment on one line.
        assert_eq!(
            trailing_frame_content("BEGIN;\nCOMMIT;\n/* note */ DROP TABLE t;\n"),
            Some((3, "DROP TABLE t;".to_string()))
        );
        // A `/*` only MID-line does not open a block (fail-closed:
        // string bytes are indistinguishable from code here) — the
        // line is the offender and nothing after it slips past.
        assert_eq!(
            trailing_frame_content("BEGIN;\nCOMMIT;\nA('/*);\nB;\n"),
            Some((3, "A('/*);".to_string()))
        );
        // An UNTERMINATED block comment after the close is trailing
        // content at its opening line: the scan cannot
        // bound what the engine reads past it — statements inside the
        // open block included.
        assert_eq!(
            trailing_frame_content("BEGIN;\nCOMMIT;\n/* note"),
            Some((3, "/* note".to_string()))
        );
        assert_eq!(
            trailing_frame_content("BEGIN;\nCOMMIT;\n/* spanning\nDROP TABLE t;\n"),
            Some((3, "/* spanning".to_string()))
        );
        // Non-canonical close spellings anchor too: the
        // engine folds case and lexer whitespace, so the guard does —
        // `commit;`, an indented close, trailing space, inner space.
        assert_eq!(
            trailing_frame_content("BEGIN;\ncommit;\nDROP TABLE t;\n"),
            Some((3, "DROP TABLE t;".to_string()))
        );
        assert_eq!(
            trailing_frame_content("BEGIN;\n  COMMIT ;\nDROP TABLE t;\n"),
            Some((3, "DROP TABLE t;".to_string()))
        );
        assert_eq!(
            trailing_frame_content("BEGIN;\nCOMMIT;\u{a0}\nDROP TABLE t;\n"),
            Some((3, "DROP TABLE t;".to_string()))
        );
        // A non-canonical close with nothing after it passes the guard
        // (NoCommit's ground at commit — splice's exact match refuses
        // it there; the tolerant anchor is push's defense-in-depth).
        assert_eq!(trailing_frame_content("BEGIN;\ncommit;\n"), None);
        // No close at all: not this guard's finding.
        assert_eq!(trailing_frame_content("BEGIN TRANSACTION;\nA;\n"), None);
    }

