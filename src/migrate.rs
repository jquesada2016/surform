    /// The render-side GRAMMAR gate: the
    /// writers refuse an `InputMode` whose label `from_label` would
    /// not parse back — a keyless tag, an unknown key, an empty
    /// value, a half versions pair — so `write_draft` cannot produce
    /// a file the crate's own parse refuses. Both-empty versions
    /// stays legal (the legacy bare posture), and every accepted
    /// shape's label round-trips (the write side is total over
    /// validated inputs).
