//! The migration FILE pipeline: `migrate generate
//! --save` writes the convergence script as a numbered, headered
//! DRAFT under the drafts directory (`migrations/` by default), and
//! `migrate commit` turns a filled draft into the committed
//! migration — hashing the filled script, marking the header, and
//! appending the migration ledger's statements INSIDE the script's
//! one transaction, so applying the file through ANY SurrealDB
//! tooling records itself (a self-describing ledger).
//!
//! # The file format (this module is the format's one home)
//!
//! ```text
//! -- surform migration 0001 — add-users
//! -- generated: 2026-10-07T18:04:05Z
//! -- source: schema.surdl
//! -- input: versions from=schema-v1.surdl to=schema-v2.surdl
//! -- status: draft
//! -- generated by `surform migrate generate` - the
//! --    convergence script.
//! …
//! BEGIN TRANSACTION;
//! …
//! COMMIT;
//! ```
//!
//! The metadata header is tool-owned (five lines, parsed by
//! [`parse_draft`]); the script below it is the convergence script
//! rendered with its REQUIRED slots delimited by git-style
//! resolution markers — bare text, not comments, so an unresolved
//! draft is deliberately UN-runnable SurrealQL (the git-merge
//! semantics): `<<<<<<< SURFORM SLOT (db:acme/shop: table stale)` …
//! `>>>>>>> SURFORM SLOT END`. Resolution = the user replaces the
//! whole delimited region with their query; the markers are gone and
//! [`scan_markers`] goes quiet. The guidance and `e.g.` lines inside
//! the region stay comments, and the `SURFORM WARNING` anchors are
//! permanent documentation in both carriers — never markers. The
//! stdout `generate` path never renders markers (its scripts run
//! today): the marker style rides the renderer's [`SlotStyle`]
//! argument, and every other byte of the script is shared.
//!
//! `commit` refuses while any marker remains (exit 1, each
//! unresolved slot named), requires `-m/--message`, and records:
//!
//! - **the hash** — SHA-256 (in-repo, see [`sha256`]) over the
//!   FILLED script body's NORMAL FORM: the bytes from
//!   `BEGIN TRANSACTION;` through `COMMIT;` inclusive, newline-
//!   normalized and EXCLUDING the appended ledger region below — the
//!   script the user certified, not the tool machinery and not the
//!   metadata header (hand-edited header comments are not drift).
//!   Hashing the normal form — not the raw bytes — makes the
//!   recorded hash a fixed point of commit's own rewrite: the splice
//!   newline-normalizes the body it writes, so an unchanged file
//!   re-derives the recorded hash exactly (a draft whose body lacked
//!   a trailing newline included). Line endings normalize at parse
//!   ([`parse_draft`]: CRLF to LF, before any offset math), so the
//!   committed file is always LF whatever the draft carried. The
//!   hash goes into the header's
//!   status line and the ledger row; `status` re-derives
//!   it with [`filled_script`] and any mismatch is DRIFTED. What is
//!   NOT drift: any edit INSIDE the appended ledger region (it is
//!   descoped from the hash by construction) — "do not edit" on the
//!   banner applies to the whole region, and an edit there surfaces
//!   at apply time (the statements execute as edited), never as a
//!   hash mismatch.
//! - **the committed header** — the status line becomes
//!   `-- status: committed sha256:<hex> <message>` (a commit message
//!   folds its line terminators to visible escapes there; the LEDGER
//!   keeps the raw message). Commit is once per file, ever: a file
//!   whose header already says `committed` refuses — hash unchanged,
//!   "already committed"; hash changed, "edited after commit" (the
//!   ledger keeps the recorded hash; the repair is a fresh draft).
//!   No amend path: the ledger's insert is idempotent per number, so
//!   a second record could not exist anyway.
//! - **the ledger statements** — spliced before the script's final
//!   `COMMIT;` ([`splice_before_commit`]), INSIDE the transaction
//!   the script already wraps (a failed statement — the insert
//!   included — rolls the whole migration back): a
//!   `DEFINE TABLE IF NOT EXISTS` for the ledger plus its typed
//!   fields (both `IF NOT EXISTS`, so the block re-runs cleanly) and
//!   ONE idempotent record insert for THIS file — `INSERT IGNORE`
//!   keyed on the record id (the migration number), so a re-run
//!   skips the row it already wrote (verified against the embedded
//!   3.3 engine and the vendored 3.3.0 sources:
//!   `surrealdb-sql`'s `InsertStatement.ignore` prints ` IGNORE`,
//!   and the executor turns the duplicate-id conflict into a skip
//!   under `is_ignore()`). `applied_at` is `time::now()` — evaluated
//!   when the script RUNS, so the ledger records the true apply
//!   time, not the commit time. The one-frame shape this leans on is
//!   ENFORCED, not assumed ([`trailing_frame_content`]): commit and
//!   push refuse any body carrying content after the frame's
//!   `COMMIT;` — the engine runs the frame and a tail independently,
//!   so a tail failure would leave the frame committed (its ledger
//!   row self-recorded) under a false "rolled back" report.
//!
//! The ledger's `sdl` column holds the canonical SDL text of the
//! flattened document the migration converges TO (the `--info`
//! mode's positional file; the version pair's `--to` file) —
//! `commit` re-loads the header's `-- source:` path and canonicalizes
//! it, fail-closed on an unreadable or dirty file. The canonical
//! flattened form, not the authored file text, is the revert
//! substrate (`status` feeds it back through the same load the
//! `--from/--to` mode runs): it is self-contained (includes already
//! resolved) and a total function of the resolved document, so the
//! recorded state is exactly what the script applies, wherever the
//! working tree has drifted since.
//!
//! The saved file is a pure function of the findings' multiset plus
//! the save options — the generated-at timestamp rides the options,
//! so pinning it pins the bytes (the permutation property the script
//! renderer carries extends through the header and markers).

