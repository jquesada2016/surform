    /// CRLF normalizes at parse — before ANY offset math: the
    /// mixed-endings draft (CRLF header, LF script region)
    /// once drifted the header offsets one byte per `\r`-stripped line
    /// while the frame find still passed, and the commit spliced the
    /// status line mid-line — silently, exit 0. Now every offset
    /// indexes `draft.text` (the LF spelling), so the mixed draft AND
    /// the all-CRLF draft parse exact, and the marked file is clean LF
    /// that re-parses to the same identity, committed.
    #[test]
    fn crlf_normalizes_before_any_offset_math() {
        let lf = draft_text();
        let header_end = lf.find("BEGIN TRANSACTION;").expect("the frame");
        let mixed = format!(
            "{}{}",
            lf[..header_end].replace('\n', "\r\n"),
            &lf[header_end..]
        );
        assert_ne!(mixed, lf, "the header is CRLF'd");
        for crlf_draft in [mixed, lf.replace('\n', "\r\n")] {
            let draft = draft_of(&crlf_draft);
            assert!(!draft.text.contains('\r'), "the parsed text is LF");
            assert_eq!(
                &draft.text[draft.status_line.0..draft.status_line.1],
                "-- status: draft"
            );
            assert!(draft.body.starts_with("BEGIN TRANSACTION;\n"));
            assert!(draft.body.ends_with("COMMIT;\n"));
            // The commit's two edits land ON the line: no `\r` rides
            // into the committed file, the status line is whole, and
            // the file re-parses to the same identity — committed.
            let hash = sha256_hex(b"x");
            let block = ledger_statements(
                DEFAULT_LEDGER_TABLE,
                1,
                "add-users",
                &hash,
                "mixed endings",
                "s",
            );
            let new_body = splice_before_commit(&draft.body, &block).expect("the frame stood");
            let committed = mark_committed(&draft, &hash, "mixed endings", &new_body);
            assert!(!committed.contains('\r'), "the committed file is LF");
            // draft_text() renders the None arm: no source-sha line,
            // so the status line is the fifth header line.
            assert_eq!(
                committed.lines().nth(4).expect("the status line"),
                format!("-- status: committed sha256:{hash} mixed endings")
            );
            let redraft = draft_of(&committed);
            assert_eq!(redraft.header.number, draft.header.number);
            assert_eq!(redraft.header.name, draft.header.name);
            assert_eq!(redraft.header.generated, draft.header.generated);
            assert_eq!(redraft.header.source, draft.header.source);
            assert_eq!(redraft.header.input, draft.header.input);
            assert_eq!(
                redraft.header.committed,
                Some(Committed {
                    hash,
                    message: "mixed endings".to_string(),
                })
            );
        }
    }

