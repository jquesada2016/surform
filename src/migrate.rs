/// The draft header's first-line prefix — the one spelling of the
/// format's identity line: [`render_draft`] prints it, and
/// [`parse_draft`] and `renumber_draft` strip it. `fmt`'s
/// migration-script refusal anchors its detector on the same
/// constant (a file opening with it is a migration script, and `--`
/// is SurrealQL comment syntax, not SDL's — the parse would die in a
/// wall of SDL-E1001/E1002 instead of one clear refusal).
pub const DRAFT_HEADER_PREFIX: &str = "-- surform migration ";

/// Whether `text` opens with the migration draft header's first line
/// ([`DRAFT_HEADER_PREFIX`]) — the detector `fmt` gates every mode
/// on, file and stdin alike. Prefix-anchored, deliberately looser
/// than [`parse_draft`]'s full structured parse: anything declaring
/// itself a migration script is not SDL for `fmt` to reflow,
/// malformed header or not.
pub fn opens_with_draft_header(text: &str) -> bool {
    text.lines()
        .next()
        .is_some_and(|first| first.starts_with(DRAFT_HEADER_PREFIX))
}

/// The appended ledger region's first line ([`filled_script`] strips
/// from the line spelling EXACTLY this — the splice's one spelling —
/// when it re-derives the committed hash).
const LEDGER_BANNER: &str =
    "-- surform: migration ledger — appended by `surform migrate commit`; do not edit.";

/// The filled script's hash — SHA-256 over its UTF-8 bytes, spelled
/// lowercase hex (the header's and the ledger's form).
pub fn sha256_hex(bytes: &[u8]) -> String {
    sha256::hex(sha256::digest(bytes))
}

/// The input modes, as the header records and re-parses them —
/// the diff's INPUTS, not just its class (issue #75): the header is
/// billed as the migration's identity, and a half-identity (a
/// `versions` line naming neither file, an `info` line keeping no tag
/// paths) cannot say what the migration converged from. The recorded
/// spellings ride the CLI arguments verbatim (paths as given, tag
/// specs as given), so the round trip recovers exactly what was
/// diffed.
///
/// # The `-- input:` line's grammar
///
/// ```text
/// -- input: info <tag>…            tags: root=<path> | ns=<name>=<path> | db=<ns>/<db>=<path>
/// -- input: versions from=<file> to=<file>
/// -- input: file path=<file>
/// ```
///
/// Tokens are whitespace-separated `key=value`; a value carrying
/// whitespace rides double-quoted (`from="my file.surdl"` — the one
/// escaping story, see [`InputMode::spell_value`]); a value carrying
/// a double quote or a control character cannot ride the line at all
/// ([`InputMode::validate`], which the writers enforce). The parse
/// ([`InputMode::from_label`]) is the exact inverse and STRICT: an
/// unknown key, a missing value, a partial `versions` pair, or a
/// malformed token refuses the draft. The bare spellings (`info`,
/// `versions`, no details) parse as the LEGACY posture — drafts
/// predating the extended line — and are never rendered by the
/// writers (generate always names its file pair, its tags, or its
/// baseline file; revert its `from=(live) to=<sidecar>`); the `file`
/// mode takes exactly one `path=` token and has no bare posture.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum InputMode {
    /// The SDL file against rendered INFO interchange (`--info`) —
    /// the tag specs as given, in the order given.
    Info { tags: Vec<String> },
    /// Schema version against schema version (`--from`/`--to`) — the
    /// two paths as given. Revert records `from=(live)` (the live
    /// schema has no file spelling) and the sidecar's path as `to`.
    Versions { from: String, to: String },
    /// The SDL-only baseline (the bare FILE, issue #101) — the file
    /// is the TO side and the FROM side is empty, so every finding is
    /// apply-pending. The header records the file's path as given.
    File { path: String },
}

/// A recorded value's wire spelling: quoted when it carries
/// whitespace (the token grammar's quote rule), raw otherwise.
/// INFALLIBLE by design but NOT total over arbitrary strings — a
/// value carrying a double quote or a control character would spell a
/// corrupt token; [`InputMode::validate`] refuses that class before
/// any writer renders, and [`render_draft`] documents the
/// precondition.
fn spell_value(value: &str) -> String {
    if value.chars().any(char::is_whitespace) {
        format!("\"{value}\"")
    } else {
        value.to_string()
    }
}

/// One token's value read back: a double-quoted segment strips its
/// quotes; a raw value rides as spelled. (Control characters cannot
/// appear in any token — the tokenizer refuses them everywhere.)
fn read_value(value: &str) -> Option<String> {
    match value.strip_prefix('"') {
        Some(inner) => inner.strip_suffix('"').map(str::to_string),
        None => Some(value.to_string()),
    }
}

/// The payload's tokens: whitespace-separated, with a double-quoted
/// segment (and the whitespace inside it) riding as ONE token — the
/// quote may sit mid-token (`from="my file.surdl"`). A malformed
/// quote — an unterminated segment, text glued after a closing
/// quote, a second segment in one token, a control character
/// anywhere — refuses the whole line (the parse is strict; a
/// half-understood header is worse than a refused one).
fn input_tokens(payload: &str) -> Option<Vec<String>> {
    let mut tokens = Vec::new();
    let mut token = String::new();
    let mut in_quote = false;
    // This token already carried a quoted segment: only whitespace
    // may follow its closing quote.
    let mut quoted = false;
    for ch in payload.chars() {
        match ch {
            '"' => {
                if in_quote {
                    in_quote = false;
                    quoted = true;
                } else if quoted {
                    return None; // a second quoted segment in one token
                } else {
                    in_quote = true;
                }
                token.push(ch);
            }
            c if c.is_whitespace() && !in_quote => {
                if !token.is_empty() {
                    tokens.push(std::mem::take(&mut token));
                    quoted = false;
                }
            }
            c => {
                if quoted {
                    return None; // text glued after a closing quote
                }
                if (c as u32) < 0x20 || c as u32 == 0x7F {
                    return None; // control characters cannot ride any token
                }
                token.push(ch);
            }
        }
    }
    if in_quote {
        return None; // unterminated quoted segment
    }
    if !token.is_empty() {
        tokens.push(token);
    }
    Some(tokens)
}

impl InputMode {
    /// The header line's spelling — mode word plus the recorded
    /// values (the legacy bare spellings for the pre-#75 posture,
    /// which the writers never render). Values with whitespace ride
    /// quoted; [`InputMode::validate`] refuses the unspellable class
    /// before any writer gets here.
    pub fn label(&self) -> String {
        match self {
            InputMode::Info { tags } if tags.is_empty() => "info".to_string(),
            InputMode::Info { tags } => {
                // Each tag rides `key=<value>`: the value part quotes,
                // the key never (the parse splits on the FIRST `=` and
                // checks the key, so quoting the whole spec would
                // corrupt the key it protects).
                let spelled: Vec<String> = tags
                    .iter()
                    .map(|tag| match tag.split_once('=') {
                        Some((key, value)) => format!("{key}={}", spell_value(value)),
                        None => spell_value(tag),
                    })
                    .collect();
                format!("info {}", spelled.join(" "))
            }
            InputMode::Versions { from, to } if from.is_empty() && to.is_empty() => {
                "versions".to_string()
            }
            InputMode::Versions { from, to } => {
                format!("versions from={} to={}", spell_value(from), spell_value(to))
            }
            InputMode::File { path } => format!("file path={}", spell_value(path)),
        }
    }

    /// The header line's inverse (parse-side): the extended grammar
    /// above, the bare spellings as the legacy posture, `None` for
    /// anything else — a [`DraftError::MalformedHeader`] at the
    /// caller. Info keys may repeat (different scopes ride separate
    /// tags); the versions pair requires `from` and `to`, each once;
    /// the file mode requires exactly one `path` token.
    pub fn from_label(payload: &str) -> Option<Self> {
        match payload {
            "info" => return Some(InputMode::Info { tags: Vec::new() }),
            "versions" => {
                return Some(InputMode::Versions {
                    from: String::new(),
                    to: String::new(),
                });
            }
            _ => {}
        }
        let (mode, rest) = payload.split_once(' ')?;
        let tokens = input_tokens(rest)?;
        match mode {
            "info" => {
                let mut tags = Vec::new();
                for token in tokens {
                    let (key, value) = token.split_once('=')?;
                    if !matches!(key, "root" | "ns" | "db") || value.is_empty() {
                        return None;
                    }
                    // The spec records WHOLE, as given (`root=<path>`,
                    // `ns=<name>=<path>` — the value's quotes stripped
                    // back off): the recorded tag spells the CLI's
                    // argument, so the round trip recovers it exactly.
                    tags.push(format!("{key}={}", read_value(value)?));
                }
                Some(InputMode::Info { tags })
            }
            "versions" => {
                // Boundary whitespace only (`versions `): the legacy
                // bare posture, exactly like the payload match above.
                if tokens.is_empty() {
                    return Some(InputMode::Versions {
                        from: String::new(),
                        to: String::new(),
                    });
                }
                let mut from: Option<String> = None;
                let mut to: Option<String> = None;
                for token in tokens {
                    let (key, value) = token.split_once('=')?;
                    let value = match (key, value.is_empty()) {
                        ("from", false) if from.is_none() => read_value(value)?,
                        ("to", false) if to.is_none() => read_value(value)?,
                        _ => return None,
                    };
                    match key {
                        "from" => from = Some(value),
                        _ => to = Some(value),
                    }
                }
                Some(InputMode::Versions {
                    from: from?,
                    to: to?,
                })
            }
            "file" => {
                // Exactly one `path=` token; no bare posture (the mode
                // is brand new — a header spelling `file` alone never
                // existed to stay readable).
                let [token] = tokens.as_slice() else {
                    return None;
                };
                let (key, value) = token.split_once('=')?;
                if key != "path" || value.is_empty() {
                    return None;
                }
                Some(InputMode::File {
                    path: read_value(value)?,
                })
            }
            _ => None,
        }
    }

    /// The writers' render-side gate — the parse's own accepted set,
    /// enforced before any file lands: every `--info` tag spells
    /// `key=value` with a known key (`root`/`ns`/`db`) and a non-empty
    /// value, and the versions pair names BOTH files or neither (both
    /// empty is the legacy bare posture the parse keeps; a half pair
    /// has no spelling). ON TOP of the grammar, a recorded value
    /// carrying a double quote or a control character refuses (a
    /// newline would forge header lines outright). Whitespace is FINE
    /// (it quotes). Either class refuses the save — naming the
    /// offender — instead of writing a header
    /// [`InputMode::from_label`] would refuse downstream.
    pub fn validate(&self) -> Result<(), DraftError> {
        match self {
            InputMode::Info { tags } => {
                for tag in tags {
                    let well_formed = match tag.split_once('=') {
                        Some((key, value)) => {
                            matches!(key, "root" | "ns" | "db") && !value.is_empty()
                        }
                        None => false,
                    };
                    if !well_formed {
                        return Err(DraftError::InputSpecUnusable { spec: tag.clone() });
                    }
                }
            }
            InputMode::Versions { from, to } => {
                if from.is_empty() != to.is_empty() {
                    return Err(DraftError::InputSpecUnusable {
                        spec: format!("from={from} to={to}"),
                    });
                }
            }
            InputMode::File { path } => {
                if path.is_empty() {
                    return Err(DraftError::InputSpecUnusable {
                        spec: "file path=".to_string(),
                    });
                }
            }
        }
        let values: Vec<&str> = match self {
            InputMode::Info { tags } => tags.iter().map(String::as_str).collect(),
            InputMode::Versions { from, to } => vec![from, to],
            InputMode::File { path } => vec![path],
        };
        for value in values {
            if value.contains('"') || value.bytes().any(|b| b < 0x20 || b == 0x7F) {
                return Err(DraftError::InputValueUnusable {
                    value: value.to_string(),
                });
            }
        }
        Ok(())
    }
}

