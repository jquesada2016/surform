    /// The `-- input:` line's grammar (issue #75): all three modes
    /// round-trip through label ∘ from_label, the legacy bare
    /// spellings still parse (drafts predating the line), the quoted
    /// value rides whitespace through the round trip, and every
    /// malformed shape refuses the parse.
    #[test]
    fn input_line_grammar_round_trips_and_refuses() {
        // All three modes, full payloads.
        let versions = versions_input("schema-v1.surdl", "schema-v2.surdl");
        assert_eq!(
            versions.label(),
            "versions from=schema-v1.surdl to=schema-v2.surdl"
        );
        assert_eq!(InputMode::from_label(&versions.label()), Some(versions));
        let tags = info_input(&[
            "root=info-root.txt",
            "ns=test=info-ns.txt",
            "db=test/scratch=info-db.txt",
        ]);
        assert_eq!(
            tags.label(),
            "info root=info-root.txt ns=test=info-ns.txt db=test/scratch=info-db.txt"
        );
        assert_eq!(InputMode::from_label(&tags.label()), Some(tags.clone()));
        // The baseline's single token (issue #101).
        let file = InputMode::File {
            path: "schema.surdl".to_string(),
        };
        assert_eq!(file.label(), "file path=schema.surdl");
        assert_eq!(InputMode::from_label(&file.label()), Some(file));
        // The legacy bare spellings parse — with empty details, the
        // posture the writers never render.
        assert_eq!(
            InputMode::from_label("info"),
            Some(InputMode::Info { tags: Vec::new() })
        );
        assert_eq!(
            InputMode::from_label("versions"),
            Some(InputMode::Versions {
                from: String::new(),
                to: String::new()
            })
        );
        // Whitespace rides quoted, both spellings round-tripping.
        let spaced = versions_input("my schemas/v1.surdl", "schemas-v2.surdl");
        assert_eq!(
            spaced.label(),
            "versions from=\"my schemas/v1.surdl\" to=schemas-v2.surdl"
        );
        assert_eq!(InputMode::from_label(&spaced.label()), Some(spaced.clone()));
        let spaced_tag = info_input(&["db=test/scratch=my info/db.txt"]);
        assert_eq!(InputMode::from_label(&spaced_tag.label()), Some(spaced_tag));
        let spaced_file = InputMode::File {
            path: "my schemas/x.surdl".to_string(),
        };
        assert_eq!(spaced_file.label(), "file path=\"my schemas/x.surdl\"");
        assert_eq!(
            InputMode::from_label(&spaced_file.label()),
            Some(spaced_file)
        );
        // The refusals: unknown mode, unknown key, empty value, a
        // partial versions pair, a duplicated key, a malformed token,
        // and text glued after a closing quote. The file mode has no
        // bare legacy posture — bare `file`, a keyless token, a wrong
        // key, an empty value, and a second token all refuse.
        for malformed in [
            "config x",
            "file",
            "file ",
            "file x",
            "file path=",
            "file path=a extra=b",
            "file from=a",
            "info scope=path",
            "info root=",
            "versions from=a",
            "versions to=b",
            "versions from=a to=b from=c",
            "versions from=a to=b extra=c",
            "versions a=b to=c",
            "info root=path extra",
            "versions from=\"unterminated to=b",
            "versions from=\"a\"glued to=b",
            "info \"root=a\"glued",
            "info root=\"a\"x\"b\"",
        ] {
            assert_eq!(
                InputMode::from_label(malformed),
                None,
                "`{malformed}` must refuse"
            );
        }
        // Boundary whitespace trims: `info ` and `versions ` ride
        // like the bare legacy spellings, but an unknown mode with
        // trailing space still refuses.
        assert_eq!(
            InputMode::from_label("info "),
            Some(InputMode::Info { tags: Vec::new() })
        );
        assert_eq!(
            InputMode::from_label("versions "),
            Some(InputMode::Versions {
                from: String::new(),
                to: String::new()
            })
        );
        assert_eq!(InputMode::from_label("config "), None);
    }

