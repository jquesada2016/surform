    /// The pile-up scan (issue #74): a written draft is found by its
    /// script hash — the lowest-numbered one when several stack — the
    /// header's variable payload (name, stamps, source) does not
    /// participate (the hash covers the body region only), a
    /// different script finds nothing until written, a CRLF'd
    /// write matches its LF spelling (the region normalizes exactly
    /// as the parse does), and a COMMITTED carrier drops out (the
    /// note names drafts to take over — `--replace` refuses committed
    /// targets; the committed twin surfaces at commit/push instead).
    #[test]
    fn find_identical_draft_matches_the_written_script() {
        let dir = std::env::temp_dir().join(format!("surform-n1-dup-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        assert_eq!(
            find_identical_draft(&dir, "anyhash"),
            None,
            "an absent directory holds no twin"
        );
        let first = write_draft(&dir, seed(None, "s.surdl", MARKED)).expect("the first draft");
        let hash = marked_script_hash(MARKED).expect("the marked script");
        assert_eq!(
            find_identical_draft(&dir, &hash),
            Some(first.clone()),
            "the written draft carries the script"
        );
        // The same script under a new number stacks; the scan names
        // the LOWEST — and the header's variable payload (the renamed
        // slug, the other source) never participated.
        let second = write_draft(&dir, seed(Some("Renamed!"), "other.surdl", MARKED))
            .expect("the second draft");
        assert_ne!(first, second);
        assert_eq!(
            find_identical_draft(&dir, &hash),
            Some(first),
            "the lowest-numbered twin wins"
        );
        // A different script (a one-line edit inside the frame) finds
        // nothing until it is written.
        let edited = MARKED.replace(
            "REMOVE TABLE IF EXISTS stale;",
            "REMOVE TABLE IF EXISTS gone;",
        );
        let edited_hash = marked_script_hash(&edited).expect("the edited script");
        assert_eq!(
            find_identical_draft(&dir, &edited_hash),
            None,
            "nothing carries the edited script yet"
        );
        let third = write_draft(&dir, seed(None, "s.surdl", &edited)).expect("the edited draft");
        assert_eq!(
            find_identical_draft(&dir, &edited_hash),
            Some(third.clone())
        );
        // A COMMITTED carrier drops out: commit the third file in
        // place (the real commit's header rewrite) and the edited
        // script — its only carrier — finds nothing.
        let text = std::fs::read_to_string(&third).expect("the draft reads");
        let draft = draft_of(&text);
        let filled = sha256_hex(filled_script(&draft.body).as_bytes());
        let block = ledger_statements(
            "_surform_migrations",
            3,
            "s",
            &filled,
            "m",
            "namespace test;\n",
        );
        let new_body = splice_before_commit(&draft.body, &block).expect("the splice");
        std::fs::write(&third, mark_committed(&draft, &filled, "m", &new_body))
            .expect("the commit writes");
        assert_eq!(
            find_identical_draft(&dir, &edited_hash),
            None,
            "the committed carrier is skipped"
        );
        let _ = std::fs::remove_dir_all(&dir);
        // CRLF, in a directory of its own (the LF draft would shadow
        // the match): the written bytes carry them verbatim, the hash
        // does not — both sides normalize like the parse does.
        let crlf_dir =
            std::env::temp_dir().join(format!("surform-n1-dup-crlf-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&crlf_dir);
        let crlf = MARKED.replace('\n', "\r\n");
        let crlf_draft =
            write_draft(&crlf_dir, seed(None, "s.surdl", &crlf)).expect("the CRLF draft");
        let text = std::fs::read_to_string(&crlf_draft).expect("the CRLF draft reads");
        assert!(text.contains('\r'), "the write is verbatim");
        assert_eq!(
            find_identical_draft(&crlf_dir, &hash),
            Some(crlf_draft),
            "the CRLF spelling matches the LF hash"
        );
        let _ = std::fs::remove_dir_all(&crlf_dir);
    }

    /// `--replace <n>` (issue #74): an identical script takes the
    /// number (the stale file gone, the parsed identity intact), a
    /// DIFFERENT script refuses with both hashes and the target
    /// survives, a committed target refuses (history is not
    /// replaceable), and a missing number refuses.
    #[test]
    fn replace_draft_takes_the_number_through_the_hash_gate() {
        let dir = std::env::temp_dir().join(format!("surform-n1-rep-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        // A missing target refuses before anything else.
        assert_eq!(
            replace_draft(&dir, 7, seed(None, "s.surdl", MARKED)).unwrap_err(),
            DraftError::ReplaceTargetMissing { number: 7 }
        );
        let stale = write_draft(&dir, seed(None, "s.surdl", MARKED)).expect("the stale draft");
        // The identical script replaces: same number (here the same
        // name slug, so the same path), the file parses to the same
        // identity.
        let replaced = replace_draft(&dir, 1, seed(None, "s.surdl", MARKED)).expect("the replace");
        assert_eq!(replaced, stale, "the number carries over");
        assert!(replaced.exists(), "the draft exists");
        let text = std::fs::read_to_string(&replaced).expect("the replaced draft reads");
        assert_eq!(draft_of(&text).header.number, 1);
        // A different script refuses; both hashes ride; the target
        // survives the refusal.
        let edited = MARKED.replace(
            "REMOVE TABLE IF EXISTS stale;",
            "REMOVE TABLE IF EXISTS gone;",
        );
        let error = replace_draft(&dir, 1, seed(None, "s.surdl", &edited))
            .expect_err("a different script refuses");
        let DraftError::ReplaceScriptMismatch {
            recorded, current, ..
        } = &error
        else {
            panic!("the mismatch refusal, got {error}");
        };
        assert_ne!(recorded, current, "the two hashes differ");
        assert_eq!(current, &marked_script_hash(&edited).unwrap());
        assert!(
            error.to_string().contains("does not carry this script"),
            "{error}"
        );
        assert!(replaced.exists(), "the target survives the refusal");
        // A committed target refuses — history is not replaceable.
        let draft = draft_of(&text);
        let hash = sha256_hex(filled_script(&draft.body).as_bytes());
        let block = ledger_statements(
            "_surform_migrations",
            1,
            "s",
            &hash,
            "m",
            "namespace test;\n",
        );
        let new_body = splice_before_commit(&draft.body, &block).expect("the splice");
        std::fs::write(&replaced, mark_committed(&draft, &hash, "m", &new_body))
            .expect("the commit writes");
        assert_eq!(
            replace_draft(&dir, 1, seed(None, "s.surdl", MARKED)).unwrap_err(),
            DraftError::ReplaceCommitted { number: 1 }
        );
        assert!(replaced.exists(), "the committed file survives");
        let _ = std::fs::remove_dir_all(&dir);
    }

